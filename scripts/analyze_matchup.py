"""Fast V2 matchup analysis using the same frozen models and equivalent pre-event features."""
import argparse,json,re,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
import joblib
import numpy as np
import pandas as pd
from sportslab.data import validate_events,SPORTS,sha256
from sportslab.evaluate import temperature_scale
from experiments.scenario import latest_features
from experiments.v2.run import ROOT,code_hash

def predict(sport,side_a,side_b,date,surface='all',neutral=False,rank_a=None,rank_b=None,allow_cold_start=False):
    if not re.fullmatch(r'\d{4}-\d{2}-\d{2}',date):raise ValueError('Date must be YYYY-MM-DD')
    date=pd.Timestamp(date)
    if side_a==side_b:raise ValueError('Participants must differ')
    if any(r is not None and (not np.isfinite(r) or r<=0) for r in (rank_a,rank_b)):raise ValueError('Ranks must be positive and finite')
    if sport=='tennis' and surface not in {'Hard','Clay','Grass','Carpet'}:raise ValueError('Use an explicit supported tennis surface')
    freeze_path=ROOT/'artifacts'/'v2'/'SELECTION_FREEZE.json'
    if not freeze_path.exists():raise ValueError('Matchup analysis is locked until the full four-sport benchmark is released')
    freeze=json.loads(freeze_path.read_text())
    for candidate in SPORTS:
        path=ROOT/'artifacts'/'v2'/candidate/'selection.json'
        report=ROOT/'reports'/'v2'/candidate/'evaluation.json'
        if not path.exists() or sha256(path)!=freeze['selection_hashes'].get(candidate):
            raise ValueError('All-four selection freeze mismatch')
        if not report.exists():raise ValueError('Matchup analysis is locked until all four holdout evaluations complete')
        completed=json.loads(report.read_text())
        if completed.get('status')!='completed_single_new_holdout_evaluation':
            raise ValueError('Matchup analysis is locked until all four holdout evaluations complete')
        if completed.get('selection_manifest_sha256')!=sha256(path) or completed.get('global_selection_freeze_sha256')!=sha256(freeze_path):
            raise ValueError('Evaluation report does not match the frozen selection')
    directory=ROOT/'artifacts'/'v2'/sport
    selection=json.loads((directory/'selection.json').read_text())
    if selection['code_sha256']!=code_hash() or sha256(directory/'models.joblib')!=selection['models_sha256']:
        raise ValueError('Model/code identity differs from the frozen selection')
    if date<pd.Timestamp(selection['splits']['calibration_end']):raise ValueError('Date precedes calibration cutoff')
    original_a,original_b=side_a,side_b
    swapped=sport=='tennis' and side_a>side_b
    if swapped:side_a,side_b,rank_a,rank_b=side_b,side_a,rank_b,rank_a
    history_path=ROOT/'data'/'v2'/'processed'/f'{sport}.csv'
    if sha256(history_path)!=selection['data_sha256']:raise ValueError('Historical input differs from the frozen model snapshot')
    history=validate_events(pd.read_csv(history_path,dtype={'event_id':str,'side_a':str,'side_b':str,'season':str},float_precision='round_trip'),sport)
    history=history[history.date<date].copy()
    known=set(history.side_a)|set(history.side_b)
    unknown=[x for x in (side_a,side_b) if x not in known]
    if unknown and not allow_cold_start:raise ValueError(f'Unknown participant IDs: {unknown}')
    if sport=='soccer':season=f'{date.year if date.month>=7 else date.year-1}-{(date.year+1 if date.month>=7 else date.year)%100:02d}'
    elif sport=='football':season=str(date.year if date.month>=3 else date.year-1)
    else:season=str(date.year)
    row={'event_id':'__v2_scenario__','date':date,'available_date':date,'season':season,'side_a':side_a,'side_b':side_b,
         'score_a':1,'score_b':0,'neutral':neutral or sport=='tennis','surface':surface,
         'rank_a':np.nan if rank_a is None else rank_a,'rank_b':np.nan if rank_b is None else rank_b}
    frame=latest_features(pd.concat([history,pd.DataFrame([row])],ignore_index=True),sport)
    f=frame.loc[frame.event_id.eq('__v2_scenario__')]
    # Loading pickle/joblib is safe only for artifacts generated by trusted local code.
    bundle=joblib.load(directory/'models.joblib')
    raw={name:model.predict_proba(f) for name,model in bundle['models'].items()}
    ensemble=np.tensordot(bundle['ensemble_weights'],np.stack([raw[name] for name in bundle['ensemble_names']]),axes=(0,0))
    probability=temperature_scale(ensemble,bundle['temperatures']['ensemble'])[0]
    family=[temperature_scale(raw[name],bundle['temperatures'][name])[0] for name in bundle['ensemble_names']]
    if swapped:probability=probability[::-1];family=[p[::-1] for p in family]
    names=['side_b_win','draw','side_a_win'] if sport=='soccer' else ['side_b_win','side_a_win']
    warnings=[]
    if unknown:warnings.append('Cold-start participants; limited evidence')
    if history.empty or (date-history.available_date.max()).days>120:warnings.append('Historical data is stale; this is not a live forecast')
    if sport=='tennis' and (rank_a is None or rank_b is None):warnings.append('Missing pre-tournament rankings')
    direction=-1 if swapped else 1
    return {'sport':sport,'date':str(date.date()),'side_a':original_a,'side_b':original_b,
      'probabilities':dict(zip(names,map(float,probability))),
      'target_scope':('Full-time home/draw/away result' if sport=='soccer' else 'Winner conditional on a supported completed match; retirements/walkovers/defaults excluded' if sport=='tennis' else 'Winner conditional on a completed non-tied regular-season game'),
      'base_model_side_a_probability_range':[float(min(p[-1] for p in family)),float(max(p[-1] for p in family))],
      'range_note':'Model disagreement, not a statistical confidence interval',
      'historical_inputs':{'fast_elo_a_minus_b':float(direction*f.iloc[0].fast_elo_diff*400),
        'slow_elo_a_minus_b':float(direction*f.iloc[0].slow_elo_diff*400),
        'surface_elo_a_minus_b':float(direction*f.iloc[0].batch_surface_elo_diff*400),
        '90day_weighted_result_a_minus_b':float(direction*f.iloc[0].result_90d_diff)},
      'warnings':warnings,'note':'Hypothetical pairwise scenario, not a verified scheduled fixture or guaranteed outcome',
      'model_selection_sha256':sha256(directory/'selection.json'),
      'scenario_builder_sha256':sha256(ROOT/'experiments'/'scenario.py'),
      'inference_entrypoint_sha256':sha256(Path(__file__))}

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--sport',choices=SPORTS,required=True)
    p.add_argument('--side-a',required=True);p.add_argument('--side-b',required=True);p.add_argument('--date',required=True)
    p.add_argument('--surface',default='all');p.add_argument('--neutral',action='store_true')
    p.add_argument('--rank-a',type=float);p.add_argument('--rank-b',type=float);p.add_argument('--allow-cold-start',action='store_true')
    a=p.parse_args()
    try:print(json.dumps(predict(**vars(a)),indent=2,allow_nan=False))
    except (ValueError,FileNotFoundError) as error:p.exit(2,f'Error: {error}\n')
if __name__=='__main__':main()
